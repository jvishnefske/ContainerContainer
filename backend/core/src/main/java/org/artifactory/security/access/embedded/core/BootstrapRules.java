package org.artifactory.security.access.embedded.core;

import java.time.Duration;
import java.time.Instant;
import java.time.format.DateTimeParseException;
import java.util.Objects;
import java.util.Optional;

/**
 * The initial-administrator bootstrap state machine (IA1, IA2, IA4), as pure functions over {@link BootstrapState}.
 * <p>
 * A fresh installation is {@link Unclaimed}: only the SHA-256 of the one-time setup token is kept, with its expiry
 * and whether the operator supplied it ({@link Source#FILE}, {@code INITIAL_ADMIN_TOKEN_FILE}) or it was generated
 * ({@link Source#GENERATED}). A successful claim moves to {@link Claimed} for good.
 * <p>
 * On start, {@link #decideOnStart} chooses between keeping the stored state, generating a token, or adopting the
 * supplied one. {@link #attemptClaim} checks a presented token: the token is hashed and compared with
 * {@link EaHashes#constantTimeEquals}, and every refusal (already claimed, expired, wrong, malformed) carries the same
 * {@link #GENERIC_REFUSAL} reason, so a caller cannot learn which applied; {@link #classifyClaim} gives the precise
 * {@link ClaimVerdict} for server-side logs. A token is expired when {@code now} is at or after its expiry.
 * <p>
 * {@link #serialise} and {@link #parse} convert the state to and from a single line for a key-value table.
 */
public final class BootstrapRules {

    /** The shortest accepted setup token: 22 characters, about 128 bits in base64url. */
    public static final int MIN_TOKEN_LENGTH = 22;
    /** The longest accepted setup token. */
    public static final int MAX_TOKEN_LENGTH = 1024;
    /** The default lifetime of a setup token (IA2). */
    public static final Duration DEFAULT_TOKEN_TTL = Duration.ofHours(24);
    /** The one reason given for every refused claim (IA4). */
    public static final String GENERIC_REFUSAL = "invalid or expired setup token";

    private static final String VERSION = "v1";
    private static final String SEPARATOR = ";";
    private static final int MAX_CLIENT_LENGTH = 255;

    private BootstrapRules() {
    }

    /** Where the current setup token came from. */
    public enum Source {
        /** Supplied by the operator through {@code INITIAL_ADMIN_TOKEN_FILE}. */
        FILE,
        /** Generated by the server and written to {@code initial-admin.token}. */
        GENERATED
    }

    /** The closed set of bootstrap states. */
    public sealed interface BootstrapState {
    }

    /**
     * The server has not been claimed.
     *
     * @param tokenSha256 the lower-case SHA-256 hex of the setup token
     * @param expiresAt   when the setup token stops being accepted
     * @param source      where the token came from
     */
    public record Unclaimed(String tokenSha256, Instant expiresAt, Source source) implements BootstrapState {
        /** Validates the fields. */
        public Unclaimed {
            if (!EaHashes.isSha256Hex(tokenSha256)) {
                throw new IllegalArgumentException("tokenSha256 must be a SHA-256 hex digest");
            }
            Objects.requireNonNull(expiresAt, "expiresAt");
            Objects.requireNonNull(source, "source");
        }

        /**
         * Tells whether the token is expired.
         *
         * @param now the current time
         * @return {@code true} if {@code now} is at or after {@link #expiresAt()}
         */
        public boolean isExpiredAt(Instant now) {
            return !now.isBefore(expiresAt);
        }
    }

    /**
     * The server has been claimed.
     *
     * @param at       when the claim succeeded
     * @param clientIp the client address that claimed it: 1 to 255 characters, no {@code ;} or control characters
     */
    public record Claimed(Instant at, String clientIp) implements BootstrapState {
        /** Validates the fields. */
        public Claimed {
            Objects.requireNonNull(at, "at");
            if (!isStorableClient(clientIp)) {
                throw new IllegalArgumentException("clientIp is empty, too long or contains forbidden characters");
            }
        }
    }

    /** What the server must do about the setup token when it starts. */
    public sealed interface StartDecision {
    }

    /**
     * The stored state stays as it is: the server is claimed, or the stored unclaimed token is still valid.
     *
     * @param state the stored state
     */
    public record Keep(BootstrapState state) implements StartDecision {
    }

    /**
     * Generate a new token, write its file, and store {@link #unclaimed} of it with {@link Source#GENERATED}.
     *
     * @param reason why a token must be generated
     */
    public record Generate(GenerateReason reason) implements StartDecision {
    }

    /**
     * Store this state for the operator-supplied token; nothing is generated.
     *
     * @param state the new state
     */
    public record UseSupplied(Unclaimed state) implements StartDecision {
    }

    /** Why {@link Generate} was decided. */
    public enum GenerateReason {
        /** There is no stored state: first start. */
        FIRST_START,
        /** The stored token expired; it is replaced. */
        EXPIRED,
        /** The stored token was supplied by file, and no file is supplied now. */
        SUPPLIED_TOKEN_WITHDRAWN
    }

    /** The precise result of checking a claim, for server-side logs only. */
    public enum ClaimVerdict {
        /** The token matched and the claim may proceed. */
        ACCEPTED,
        /** The server is already claimed. */
        ALREADY_CLAIMED,
        /** The token is not a well-formed setup token. */
        MALFORMED,
        /** The setup token is expired. */
        EXPIRED,
        /** The token does not match. */
        MISMATCH
    }

    /**
     * Decides what to do about the setup token on start.
     * <ul>
     *     <li>Claimed: {@link Keep}; a supplied token is ignored.</li>
     *     <li>A supplied token that is malformed: {@code Refused}.</li>
     *     <li>A supplied token equal to the stored {@link Source#FILE} token: {@link Keep} while it is valid, and
     *     {@code Refused} once it has expired, because the server cannot replace an operator's file.</li>
     *     <li>Any other supplied token: {@link UseSupplied} with a fresh expiry of {@code now + ttl}.</li>
     *     <li>No supplied token and no state: {@link Generate} ({@link GenerateReason#FIRST_START}).</li>
     *     <li>No supplied token and a stored {@link Source#FILE} token: {@link Generate}
     *     ({@link GenerateReason#SUPPLIED_TOKEN_WITHDRAWN}).</li>
     *     <li>No supplied token and a stored generated token: {@link Keep} while valid, otherwise {@link Generate}
     *     ({@link GenerateReason#EXPIRED}).</li>
     * </ul>
     *
     * @param stored   the stored state, if any
     * @param supplied the operator-supplied token after {@link #normaliseSupplied}, if any
     * @param now      the current time
     * @param ttl      the token lifetime, positive
     * @return the decision, or {@code Refused}
     */
    public static EaOutcome<StartDecision> decideOnStart(Optional<BootstrapState> stored, Optional<String> supplied,
            Instant now, Duration ttl) {
        if (ttl == null || ttl.isNegative() || ttl.isZero()) {
            return EaOutcome.refused("setup token lifetime must be positive");
        }
        BootstrapState state = stored.orElse(null);
        if (state instanceof Claimed) {
            return EaOutcome.ok(new Keep(state));
        }
        Unclaimed unclaimed = (Unclaimed) state;
        if (supplied.isPresent()) {
            String token = supplied.get();
            if (!isWellFormedToken(token)) {
                return EaOutcome.refused("supplied setup token must be " + MIN_TOKEN_LENGTH + " to "
                        + MAX_TOKEN_LENGTH + " printable characters without spaces");
            }
            if (unclaimed != null && unclaimed.source() == Source.FILE && EaHashes.constantTimeEquals(
                    EaHashes.fromHex(unclaimed.tokenSha256()), EaHashes.sha256(token))) {
                return unclaimed.isExpiredAt(now)
                        ? EaOutcome.refused("supplied setup token has expired; supply a new one")
                        : EaOutcome.ok(new Keep(unclaimed));
            }
            return unclaimed(token, now, ttl, Source.FILE).map(UseSupplied::new);
        }
        if (unclaimed == null) {
            return EaOutcome.ok(new Generate(GenerateReason.FIRST_START));
        }
        if (unclaimed.source() == Source.FILE) {
            return EaOutcome.ok(new Generate(GenerateReason.SUPPLIED_TOKEN_WITHDRAWN));
        }
        return unclaimed.isExpiredAt(now)
                ? EaOutcome.ok(new Generate(GenerateReason.EXPIRED))
                : EaOutcome.ok(new Keep(unclaimed));
    }

    /**
     * Builds the unclaimed state for a token.
     *
     * @param token  the setup token in clear; only its hash is kept
     * @param now    the current time
     * @param ttl    the token lifetime, positive
     * @param source where the token came from
     * @return the state, or {@code Refused} if the token is malformed or the lifetime is not positive
     */
    public static EaOutcome<Unclaimed> unclaimed(String token, Instant now, Duration ttl, Source source) {
        if (!isWellFormedToken(token)) {
            return EaOutcome.refused("setup token is malformed");
        }
        if (ttl == null || ttl.isNegative() || ttl.isZero()) {
            return EaOutcome.refused("setup token lifetime must be positive");
        }
        return EaOutcome.ok(new Unclaimed(EaHashes.sha256Hex(token), now.plus(ttl), source));
    }

    /**
     * Normalises the content of a supplied token file by stripping leading and trailing white space (a trailing
     * newline is common in mounted secrets).
     *
     * @param fileContent the file content
     * @return the token, or empty if nothing is left
     */
    public static Optional<String> normaliseSupplied(String fileContent) {
        if (fileContent == null) {
            return Optional.empty();
        }
        String stripped = fileContent.strip();
        return stripped.isEmpty() ? Optional.empty() : Optional.of(stripped);
    }

    /**
     * Tells whether a token has the setup-token format: {@value #MIN_TOKEN_LENGTH} to {@value #MAX_TOKEN_LENGTH}
     * characters, each printable ASCII other than space ({@code !} to {@code ~}).
     *
     * @param token the token, or {@code null}
     * @return {@code true} if well formed
     */
    public static boolean isWellFormedToken(String token) {
        if (token == null || token.length() < MIN_TOKEN_LENGTH || token.length() > MAX_TOKEN_LENGTH) {
            return false;
        }
        for (int i = 0; i < token.length(); i++) {
            char c = token.charAt(i);
            if (c < '!' || c > '~') {
                return false;
            }
        }
        return true;
    }

    /**
     * Classifies a claim attempt precisely. The presented token is hashed whenever it is well formed, whatever
     * the state, and the comparison runs in constant time.
     *
     * @param state     the current state
     * @param presented the token presented by the client, or {@code null}
     * @param now       the current time
     * @return the verdict
     */
    public static ClaimVerdict classifyClaim(BootstrapState state, String presented, Instant now) {
        boolean wellFormed = isWellFormedToken(presented);
        byte[] presentedHash = wellFormed ? EaHashes.sha256(presented) : null;
        return switch (Objects.requireNonNull(state, "state")) {
            case Claimed claimed -> ClaimVerdict.ALREADY_CLAIMED;
            case Unclaimed unclaimed -> {
                if (!wellFormed) {
                    yield ClaimVerdict.MALFORMED;
                }
                boolean match = EaHashes.constantTimeEquals(EaHashes.fromHex(unclaimed.tokenSha256()),
                        presentedHash);
                if (unclaimed.isExpiredAt(now)) {
                    yield ClaimVerdict.EXPIRED;
                }
                yield match ? ClaimVerdict.ACCEPTED : ClaimVerdict.MISMATCH;
            }
        };
    }

    /**
     * Attempts a claim. On success returns the {@link Claimed} state to store (in the same transaction as the new
     * password); every refusal has the reason {@link #GENERIC_REFUSAL}.
     *
     * @param state     the current state
     * @param presented the token presented by the client
     * @param now       the current time
     * @param clientIp  the client address, recorded in the claimed state
     * @return the claimed state, or {@code Refused(GENERIC_REFUSAL)}
     */
    public static EaOutcome<Claimed> attemptClaim(BootstrapState state, String presented, Instant now,
            String clientIp) {
        if (classifyClaim(state, presented, now) != ClaimVerdict.ACCEPTED) {
            return EaOutcome.refused(GENERIC_REFUSAL);
        }
        return EaOutcome.ok(new Claimed(now, isStorableClient(clientIp) ? clientIp : "unknown"));
    }

    /**
     * Tells whether the server has been claimed.
     *
     * @param state the stored state, if any; no state means unclaimed
     * @return {@code true} for {@link Claimed}
     */
    public static boolean isClaimed(Optional<BootstrapState> state) {
        return state.filter(Claimed.class::isInstance).isPresent();
    }

    /**
     * Serialises a state to one line: {@code v1;unclaimed;<sha256>;<ISO instant>;<source>} or
     * {@code v1;claimed;<ISO instant>;<client>}.
     *
     * @param state the state
     * @return the text form
     */
    public static String serialise(BootstrapState state) {
        return switch (Objects.requireNonNull(state, "state")) {
            case Unclaimed u -> String.join(SEPARATOR, VERSION, "unclaimed", u.tokenSha256(),
                    u.expiresAt().toString(), u.source().name());
            case Claimed c -> String.join(SEPARATOR, VERSION, "claimed", c.at().toString(), c.clientIp());
        };
    }

    /**
     * Parses the output of {@link #serialise}.
     *
     * @param text the text form
     * @return the state, or {@code Refused} if the text is malformed
     */
    public static EaOutcome<BootstrapState> parse(String text) {
        if (text == null) {
            return EaOutcome.refused("bootstrap state is missing");
        }
        String[] parts = text.split(SEPARATOR, -1);
        try {
            if (parts.length == 5 && VERSION.equals(parts[0]) && "unclaimed".equals(parts[1])) {
                return EaOutcome.ok(new Unclaimed(parts[2], Instant.parse(parts[3]), Source.valueOf(parts[4])));
            }
            if (parts.length == 4 && VERSION.equals(parts[0]) && "claimed".equals(parts[1])) {
                return EaOutcome.ok(new Claimed(Instant.parse(parts[2]), parts[3]));
            }
        } catch (DateTimeParseException | IllegalArgumentException e) {
            return EaOutcome.refused("bootstrap state is malformed");
        }
        return EaOutcome.refused("bootstrap state has an unknown format");
    }

    private static boolean isStorableClient(String clientIp) {
        if (clientIp == null || clientIp.isEmpty() || clientIp.length() > MAX_CLIENT_LENGTH) {
            return false;
        }
        for (int i = 0; i < clientIp.length(); i++) {
            char c = clientIp.charAt(i);
            if (c < ' ' || c == 0x7f || c == ';') {
                return false;
            }
        }
        return true;
    }
}
