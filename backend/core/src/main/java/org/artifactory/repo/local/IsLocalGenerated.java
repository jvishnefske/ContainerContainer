package org.artifactory.repo.local;

import lombok.NonNull;
import org.artifactory.descriptor.repo.RepoType;

import jakarta.annotation.Nonnull;
import java.util.Set;

/**
 * @author saffih
 */
public interface IsLocalGenerated {
    /**
     * Is the file is generated by artifactory for local repository.
     * It should not be replicated (either generated or tmp).
     * <p>
     * Initial implementation must be return false;
     * Then check the failed Sanity test listing all replicated generated files
     * change the code to exclude only those file.
     * When in doubt - use that process and find what's actually generated (+ filter old obsolete files).
     */
    boolean isLocalGenerated(@Nonnull RepoType repoType, @Nonnull String repoKey, @Nonnull String path);

    /**
     * If the property is locally generated and can be generated natively in the mirrored repo, it should get excluded.
     */
    default boolean shouldExcludePropertyFromMirroring(@Nonnull RepoType repoType, @Nonnull String propertyKey) {
        return false;
    }

    /**
     * Determines whether a property should be excluded from mirroring based on its key and value.
     *
     * @param propertyKey The key of the property to check.
     * @param propValues  The value of the property.
     * @return Set of values that not should be excluded from mirroring.
     */
    default Set<String> excludePropertyValueFromMirroring(@NonNull String propertyKey,
            @NonNull Set<String> propValues, RepoType repoType) {
        return propValues;
    }
}
